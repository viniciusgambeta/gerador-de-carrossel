/** Icon by name; anything else (an emoji from older carousels) is drawn as text. */
export function SlideIcon({ name, size, strokeWidth = 2 }: { name: string; size: number; strokeWidth?: number }) {
  const Icon = ICONS[name as IconName];
  if (Icon) return <Icon size={size} strokeWidth={strokeWidth} />;
  if (!name) return null;
  return (
    <span className="emoji" style={{ fontSize: size }}>
      {name}
    </span>
  );
}
